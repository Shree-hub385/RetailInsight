
USE DATABASE RETAILINSIGHT;
USE SCHEMA RETAIL_SCHEMA;

-- 1. Total sales
SELECT SUM(TOTAL_AMOUNT) AS TOTAL_SALES
FROM RETAIL_SALES;

-- 2. Total transactions
SELECT COUNT(*) AS TOTAL_TRANSACTIONS
FROM RETAIL_SALES;

-- 3. Sales by product category
SELECT
    PRODUCT_CATEGORY,
    SUM(TOTAL_AMOUNT) AS CATEGORY_SALES
FROM RETAIL_SALES
GROUP BY PRODUCT_CATEGORY
ORDER BY CATEGORY_SALES DESC;

-- 4. Monthly sales
SELECT
    YEAR,
    MONTH,
    SUM(TOTAL_AMOUNT) AS MONTHLY_SALES
FROM RETAIL_SALES
GROUP BY YEAR, MONTH
ORDER BY YEAR, MONTH;

-- 5. Sales by gender
SELECT
    GENDER,
    SUM(TOTAL_AMOUNT) AS TOTAL_SALES
FROM RETAIL_SALES
GROUP BY GENDER;

-- 6. Average transaction amount
SELECT AVG(TOTAL_AMOUNT) AS AVERAGE_SALE
FROM RETAIL_SALES;
