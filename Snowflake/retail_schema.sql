
-- RetailInsight: Database Setup

CREATE DATABASE IF NOT EXISTS RETAILINSIGHT;

USE DATABASE RETAILINSIGHT;

-- Create schema
CREATE SCHEMA IF NOT EXISTS RETAIL_SCHEMA;

USE SCHEMA RETAIL_SCHEMA;

-- Create retail sales table
CREATE TABLE IF NOT EXISTS RETAIL_SALES (
    TRANSACTION_ID VARCHAR(50),
    DATE DATE,
    CUSTOMER_ID VARCHAR(50),
    GENDER VARCHAR(20),
    AGE INTEGER,
    PRODUCT_CATEGORY VARCHAR(100),
    QUANTITY INTEGER,
    PRICE_PER_UNIT DECIMAL(10,2),
    TOTAL_AMOUNT DECIMAL(10,2),
    YEAR INTEGER,
    MONTH INTEGER
);

-- Check table structure
DESCRIBE TABLE RETAIL_SALES;

-- View retail sales records
SELECT * FROM RETAIL_SALES LIMIT 10;
